"""Check that every destination in _redirects exists in the built book.

For each rule, the destination page must exist under _book/ (a directory
counts through its index.html) and, if the destination has a #section
anchor, that anchor must be an id on the page. Rules sending an old address
to another site are only checked for being well formed.

Exits non-zero if any destination is missing, so it can run in CI after
`quarto render`. _redirects is generated by migration/migrate.py; fix
problems there, not in the file.

Usage (from the repository root):
    python3 migration/check_redirects.py [--book _book] [--redirects _redirects]
"""
import argparse
import os
import re
import sys
from html.parser import HTMLParser
from urllib.parse import unquote, urlsplit

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


class Ids(HTMLParser):
    """Collects the id and name attributes of a page."""

    def __init__(self):
        super().__init__()
        self.ids = set()

    def handle_starttag(self, tag, attrs):
        for k, v in attrs:
            if k in ("id", "name") and v:
                self.ids.add(v)


def page_ids(path, cache):
    if path not in cache:
        parser = Ids()
        with open(path, encoding="utf-8") as f:
            parser.feed(f.read())
        cache[path] = parser.ids
    return cache[path]


def find_page(book, path):
    target = os.path.join(book, unquote(path).lstrip("/"))
    if os.path.isdir(target):
        target = os.path.join(target, "index.html")
    return target if os.path.isfile(target) else None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--book", default=os.path.join(ROOT, "_book"))
    ap.add_argument("--redirects", default=os.path.join(ROOT, "_redirects"))
    args = ap.parse_args()

    problems, checked, cache = [], 0, {}
    with open(args.redirects, encoding="utf-8") as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            fields = line.split()
            if len(fields) < 2:
                problems.append(f"line {n}: not 'from to [status]': {line}")
                continue
            src, dest = fields[0], fields[1]
            checked += 1
            url = urlsplit(dest)
            if url.scheme:        # another site
                continue
            page = find_page(args.book, url.path)
            if page is None:
                problems.append(f"line {n}: {src} -> {dest}: no such page")
            elif url.fragment and unquote(url.fragment) not in page_ids(
                    page, cache):
                problems.append(
                    f"line {n}: {src} -> {dest}: no #{url.fragment} on the page")

    for p in problems:
        print(p)
    print(f"{checked} redirects checked, {len(problems)} problem(s)")
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
